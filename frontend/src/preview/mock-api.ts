/**
 * ============================================================================
 * DESIGN PREVIEW ONLY — NOT FOR PRODUCTION
 * ============================================================================
 * Resolves a mocked JSON payload for the SOC frontend's `/api/*` calls using
 * the synthetic fixtures in `./fixtures`. Used exclusively by the preview
 * fetch interceptor so the authenticated UI can be inspected without the real
 * FastAPI backend. Delete the `preview/` directory to remove entirely.
 * ============================================================================
 */
import {
  chatMessages,
  dashboardSummary,
  evidenceFor,
  incidentById,
  incidentSummaries,
  events,
  report,
  wazuhStatus,
} from './fixtures'
import type { IncidentStatus } from '@/lib/types'

export interface MockResult {
  status: number
  body: unknown
}

const ok = (body: unknown): MockResult => ({ status: 200, body })

/**
 * Returns a mock result for a given API request, or null if the path is not an
 * `/api/*` route we handle (in which case the real fetch should be used).
 */
export function resolveMock(rawUrl: string, method: string): MockResult | null {
  let path = rawUrl
  try {
    // Absolute URL -> pull pathname; relative URL stays as-is.
    path = new URL(rawUrl, 'http://preview.local').pathname
  } catch {
    /* keep raw */
  }

  if (!path.startsWith('/api/')) return null

  const m = method.toUpperCase()

  // --- Auth (login is normally bypassed, but answer defensively) -----------
  if (path === '/api/auth/login' && m === 'POST') {
    return ok({ access_token: 'preview.token', token_type: 'bearer', expires_in: 86400 })
  }

  // --- Dashboard -----------------------------------------------------------
  if (path === '/api/dashboard/summary') return ok(dashboardSummary)

  // --- Incident collection + filters ---------------------------------------
  if (path === '/api/incidents' && m === 'GET') {
    return ok({ total: incidentSummaries.length, items: incidentSummaries })
  }

  // --- Incident sub-resources ----------------------------------------------
  let match: RegExpMatchArray | null

  if ((match = path.match(/^\/api\/incidents\/([^/]+)\/evidence$/))) {
    return ok({ evidence: evidenceFor(match[1]) })
  }

  if ((match = path.match(/^\/api\/incidents\/([^/]+)\/sessions$/)) && m === 'POST') {
    return ok({
      session_id: `sess-${match[1]}`,
      incident_id: match[1],
      created_at: new Date().toISOString(),
    })
  }

  if ((match = path.match(/^\/api\/incidents\/([^/]+)\/report$/)) && m === 'POST') {
    return ok({ report_id: 'rep-1001', download_url: '/api/reports/rep-1001/download' })
  }

  if ((match = path.match(/^\/api\/incidents\/([^/]+)\/status$/)) && m === 'PATCH') {
    return ok(incidentById(match[1]))
  }

  if ((match = path.match(/^\/api\/incidents\/([^/]+)$/))) {
    return ok(incidentById(match[1]))
  }

  // --- Chat sessions -------------------------------------------------------
  if ((match = path.match(/^\/api\/sessions\/([^/]+)\/messages$/))) {
    return ok({ session_id: match[1], messages: chatMessages(match[1]) })
  }

  if ((match = path.match(/^\/api\/sessions\/([^/]+)\/chat$/)) && m === 'POST') {
    return ok({
      message_id: `msg-${Date.now()}`,
      answer:
        'This is a design-preview response. In production this answer is generated by the evidence-grounded RAG pipeline against the real incident data.',
      evidence_ids: ['evd-1', 'evd-2'],
      mitre_references: ['T1110.004'],
      rag_sources: ['MITRE ATT&CK', 'Internal runbook'],
      answer_type: 'FACTUAL',
      confidence: 0.8,
    })
  }

  if ((match = path.match(/^\/api\/messages\/([^/]+)\/tts$/)) && m === 'POST') {
    return ok({ audio_clips_base64: [], content_type: 'audio/mpeg', chunk_count: 0 })
  }

  // --- Reports -------------------------------------------------------------
  if ((match = path.match(/^\/api\/reports\/([^/]+)$/))) {
    return ok(report('inc-1001'))
  }

  // --- Logs ----------------------------------------------------------------
  if (path.startsWith('/api/logs/upload') && m === 'POST') {
    return ok({
      job_id: `job-${Date.now()}`,
      events_parsed: 1284,
      events_flagged: 17,
      incidents_created: 2,
      processing_time_ms: 842,
      source_file: 'preview-upload.log',
    })
  }

  if (path.startsWith('/api/logs')) {
    return ok({ total: events.length, items: events })
  }

  // --- Wazuh integration ---------------------------------------------------
  if (path === '/api/integrations/wazuh/status') return ok(wazuhStatus)

  if (path === '/api/integrations/wazuh/poll' && m === 'POST') {
    return ok({
      status: 'ok',
      fetched: 42,
      processed: 40,
      duplicates: 2,
      watermark: new Date().toISOString(),
      errors: [],
    })
  }

  // --- NL query ------------------------------------------------------------
  if (path === '/api/nlu/query' && m === 'POST') {
    return ok({
      answer:
        'Design-preview answer: there are 2 open critical/high incidents involving external source IPs in the last 6 hours.',
      needs_clarification: false,
      clarification_question: null,
      clarification_options: [],
      result_count: 2,
      resolved_intent: 'search_incidents',
      resolved_filters: { severity: ['CRITICAL', 'HIGH'], status: ['OPEN', 'INVESTIGATING'] },
    })
  }

  // Unknown /api route: return an empty-but-valid 200 so the UI does not crash.
  return ok({})
}
